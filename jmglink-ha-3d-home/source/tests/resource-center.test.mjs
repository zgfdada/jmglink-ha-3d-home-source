for (const action of ['exit', 'publish']) test(`旧天气控件${action}无需修改即入队，重复操作去重且不上传绑定`, async t => {
  const directory = await mkdtemp(path.join(tmpdir(), 'ha3d-legacy-sharing-'));
  const app = Fastify();
  const sidebars = await SidebarStore.create(directory);
  const projects = {getProject: id => id === 'p' ? {id, floors:[{id:'f'}]} : undefined, listProjects:()=>[{id:'p'}]};
  const center = await ResourceCenter.create({directory:path.join(directory,'center'),origin:'https://resources.example.com',sidebars,projects,platform:{},fetchImpl:()=>{throw Error('local save must not fetch');}});
  await center.stopSync();
  assert.equal(center.status().silentUpload, false);
  await center.setSilentUpload(true);
  sidebars.resourceCenter = center;
  t.after(async()=>{await app.close();await center.stopSync();await rm(directory,{recursive:true,force:true});});
  await registerSidebarRoutes(app,sidebars,projects);
  const draft = defaultSidebar();
  draft.widgets[0].entityIds = ['weather.private_home'];
  draft.widgets.push({...structuredClone(draft.widgets[0]),id:'interactive',scriptMode:'dom',name:'照明开关',actions:[{id:'toggle',label:'开关',domain:'light',service:'toggle',target:'primary',data:{}}]});
  const save = (revision, value, sync = false) => app.inject({method:'PUT',url:`/api/sidebar/p/${sync && action === 'publish' ? 'publish':'draft'}?floorId=f`,payload:{revision,draft:value,syncOnExit:sync && action === 'exit'}});
  const ordinary = await save(0,draft);
  assert.equal(ordinary.statusCode,200);
  assert.equal(ordinary.json().draft.widgets[0].resourceSharing,undefined);
  assert.equal(Object.keys(center.outbox).length,0);
  const first = await save(1,ordinary.json().draft,true);
  assert.equal(first.statusCode,200,first.body);
  const result = first.json();
  assert.equal(result.draft.widgets[0].resourceSharing.version,'1.0.0');
  assert.equal(result.draft.widgets[1].resourceSharing.version,'1.0.0');
  assert.deepEqual(result.draft.widgets[0].entityIds,['weather.private_home']);
  assert.equal(Object.keys(center.outbox).length,2);
  const job = Object.values(center.outbox)[0];
  assert.equal(job.manifest.name,draft.widgets[0].name);
  assert.equal(job.state,'queued');
  const entry = job.manifest.files.find(f=>f.path===job.manifest.entry);
  const portable = JSON.parse(await readFile(path.join(directory,'center','objects',entry.sha256),'utf8'));
  assert.equal('entityIds' in portable.widget,false);
  assert.equal('entityId' in portable.widget,false);
  const second = await save(2,result.draft,true);
  assert.equal(second.statusCode,200);
  assert.equal(Object.keys(center.outbox).length,2);
  assert.equal(second.json().sync[0].id,result.sync[0].id);
  const reloaded = await SidebarStore.create(directory);
  assert.equal(reloaded.get('p').draft.widgets[0].resourceSharing.version,'1.0.0');
  if(action === 'publish')assert.equal(reloaded.get('p').published.widgets[0].resourceSharing.version,'1.0.0');
  const withPreview=structuredClone(result.draft);
  withPreview.widgets[0].resourceSharing.previewDataUrl='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jB1sAAAAASUVORK5CYII=';
  const repair=await save(3,withPreview,true);
  assert.equal(repair.statusCode,200);
  assert.equal(Object.keys(center.outbox).length,3,'缺图旧快照应允许一次带图补传');
  assert.ok(Object.values(center.outbox)[2].manifest.preview);
  const again=await save(4,repair.json().draft,true);
  assert.equal(again.statusCode,200);
  assert.equal(Object.keys(center.outbox).length,3,'已有图片后再次退出继续去重');
});

test('在线资源默认关闭且不联网，路由继承本地鉴权并拒绝跨站修改',async t=>{
  const directory=await mkdtemp(path.join(process.env.HA3D_TEST_TMP||tmpdir(),'ha3d-online-client-'));
  t.after(async()=>{if(!process.env.HA3D_TEST_TMP)await rm(directory,{recursive:true,force:true});});
  let calls=0;
  const store=await ResourceCenter.create({directory,platform:{getModelTemplates:()=>[]},projects:{listProjects:()=>[]},sidebars:{},fetchImpl:()=>{calls++;throw Error('should not fetch');}});
  assert.equal(store.status().configured,false);assert.equal(calls,0);
  const app=Fastify();t.after(()=>app.close());registerAccessPolicy(app,createAccessPolicy({token:'isolated-test-token'}));await registerResourceCenterRoutes(app,store);
  assert.equal((await app.inject('/api/resource-center/status')).statusCode,401);
  const headers={authorization:'Bearer isolated-test-token'};
  const state=await app.inject({url:'/api/resource-center/status',headers});assert.equal(state.statusCode,200);assert.equal(state.json().loggedIn,false);
  const cross=await app.inject({method:'POST',url:'/api/resource-center/login/start',headers:{...headers,'content-type':'application/json',origin:'https://other.invalid'},payload:{}});assert.equal(cross.statusCode,403);
  const form=await app.inject({method:'POST',url:'/api/resource-center/login/start',headers:{...headers,'content-type':'text/plain'},payload:''});assert.equal(form.statusCode,415);
  assert.equal(calls,0);
});

test('共享入口移除本地绑定；清单严格校验且摘要不受 JSON 键顺序影响',()=>{
  const widget=portableWidget({id:'local-private',name:'天气',kind:'custom',scriptMode:'transform',entityId:'weather.private',entityIds:['weather.private'],accountNames:{private:'家庭'},actions:[],html:'',css:'',js:'return entity;',entityDomain:'weather'});
  assert.equal('entityId' in widget.widget,false);assert.equal('accountNames' in widget.widget,false);
  assert.equal(sha256(canonical({b:1,a:2})),sha256(canonical({a:2,b:1})));
  assert.throws(()=>resourceCenterOrigin('http://192.168.31.244'));
  assert.equal(resourceCenterOrigin('https://resources.example.com'),'https://resources.example.com');
  assert.throws(()=>validateManifest({format:FORMAT,token:'must-not-be-uploaded'}));
});
