import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { copyFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
const require = createRequire(import.meta.url);
const output = new URL("../public/concept/", import.meta.url);
// Bundle the locked application engine as IIFE so the exported page works on file://.
await build({
  entryPoints: [
    fileURLToPath(new URL("../src/concept/scene.js", import.meta.url)),
  ],
  outfile: fileURLToPath(new URL("scene-runtime.js", output)),
  bundle: true,
  format: "iife",
  target: "es2022",
  minify: true,
  legalComments: "inline",
  banner: {
    js: "/* Generated by apps/web/scripts/build-concept-scene.mjs. Three.js MIT; see scene-runtime.LICENSE.txt. */",
  },
});
await build({
  entryPoints: [
    fileURLToPath(new URL("../src/concept/washer.js", import.meta.url)),
  ],
  outfile: fileURLToPath(new URL("washer-runtime.js", output)),
  bundle: true,
  format: "iife",
  target: "es2022",
  minify: true,
  loader: { ".glb": "base64" },
  legalComments: "inline",
  banner: {
    js: "/* Project washer model + shared washer-runtime.js; synthetic data only. Three.js MIT. */",
  },
});
await copyFile(
  resolve(dirname(require.resolve("three")), "../LICENSE"),
  fileURLToPath(new URL("scene-runtime.LICENSE.txt", output)),
);
